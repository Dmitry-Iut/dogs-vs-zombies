function endlessMix(w) {
  const m = { basic: 3 };
  if (w >= 2) m.helmet = 2;
  if (w >= 3) m.runner = 1.5;
  if (w >= 4) m.bucket = 1.2;
  if (w >= 5) {
    m.skater = 1.3;
    m.fatty = 0.8;
  }
  if (w >= 6) m.door = 1.2;
  if (w >= 7) m.giant = 0.25 + w * 0.03;
  return m;
}
